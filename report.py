def calculate_score(findings):
    score = 100
    for f in findings:
        sev = f.get("severity", "Low").lower()
        if sev == "critical":
            score -= 25
        elif sev == "high":
            score -= 15
        elif sev == "medium":
            score -= 10
        elif sev == "low":
            score -= 5
    return max(0, score)

def get_grade(score):
    if score >= 90:
        return "LOW RISK"
    if score >= 70:
        return "MEDIUM RISK"
    if score >= 40:
        return "HIGH RISK"
    return "CRITICAL RISK"

def generate_html_report(domain, findings, score, grade):
    rows = ""
    for f in findings:
        rows += f"""
        <tr>
            <td>{f.get('check', 'Unknown')}</td>
            <td>{f.get('severity', 'Low')}</td>
            <td>{f.get('description', '')}</td>
            <td>{f.get('fix', 'Review manually')}</td>
        </tr>
        """

    if not rows:
        rows = "<tr><td colspan='4'>No issues found - Great job!</td></tr>"

    html = f"""<!DOCTYPE html>
<html><head><meta charset="utf-8">
<title>Interstice Report - {domain}</title>
<style>
body {{ font-family: Arial; padding: 30px; background: #f4f4f4; }}
.card {{ background: white; padding: 25px; border-radius: 10px; }}
h1 {{ margin: 0; }}
.score {{ font-size: 48px; font-weight: bold; }}
table {{ width: 100%; border-collapse: collapse; margin-top: 20px; }}
th, td {{ border: 1px solid #ddd; padding: 10px; text-align: left; }}
th {{ background: #111; color: white; }}
</style></head>
<body><div class="card">
<h1>Interstice Report</h1>
<p>Domain: <b>{domain}</b></p>
<div class="score">{score}/100</div>
<p><b>{grade}</b></p>
<table><tr><th>Check</th><th>Severity</th><th>Issue</th><th>Fix</th></tr>
{rows}
</table>
<p style="margin-top:20px;color:#888;">Generated by Interstice - Find the gaps before attackers do.</p>
</div></body></html>"""

    filename = f"report_{domain.replace('.', '_')}.html"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(html)
    return filename